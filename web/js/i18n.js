const LANG_KEY = 'food_app_lang';
export let lang = localStorage.getItem(LANG_KEY) || 'fr';

export function setLang(next) {
  lang = next === 'ar' ? 'ar' : 'fr';
  localStorage.setItem(LANG_KEY, lang);
  applyDirection();
}

export function toggleLang() {
  setLang(lang === 'fr' ? 'ar' : 'fr');
}

export function applyDirection() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}

/** Translate a key, with {placeholders}. */
export function t(key, vars = {}) {
  const value = DICT[lang][key] ?? DICT.fr[key] ?? key;
  return value.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}

/** Pick the Arabic field when it exists, otherwise fall back to French. */
export function pick(row, field = 'name') {
  if (!row) return '';
  if (lang === 'ar') return row[`${field}_ar`] || row[field] || '';
  return row[field] || '';
}

